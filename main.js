// 解析题库
var questionBank = [];
rawBank.split("\n").forEach(function(line) {
    line = line.trim();
    if(line.indexOf("答案：") !== -1) {
        var parts = line.split("答案：");
        var q = parts[0].trim();
        var a = parts[1].trim();
        if(q && a) { questionBank.push({ q: q, a: a }); }
    }
});
toastLog("成功加载题库，共 " + questionBank.length + " 道纯数字答案竞赛题");

// ==================== 核心逻辑 ====================
setInterval(function() {
    if (intercepting) return; 
    var current = currentPackage();
    if (current === TARGET_APP) {
        intercepting = true;
        showMathQuestion(); 
    }
}, CHECK_INTERVAL);

function generateQuestion() {
    if (questionBank.length === 0) {
        return { text: "题库为空，请检查数据！", answer: "" };
    }
    var randomIndex = Math.floor(Math.random() * questionBank.length);
    return {
        text: questionBank[randomIndex].q,
        answer: questionBank[randomIndex].a
    };
}

// ==================== 答题弹窗 ====================
function showMathQuestion() {
    var q = generateQuestion();

    dialogs.build({
        title: "🧠 注意力竞赛",
        content: "请回答以下题目才能继续使用抖音：\n\n" + q.text,
        positive: "提交",
        negative: "放弃并退出",
        cancelable: false, 
        inputHint: "输入纯数字答案...",
        inputPrefill: ""
    }).on("positive", function(dialog, inputText) {
        // 去除首尾空格，严格匹配
        var userAnswer = inputText.trim();
        var standardAnswer = q.answer.toString().trim();

        if (userAnswer !== "" && userAnswer === standardAnswer) {
            toastLog("✅ 回答完全正确，放行");
            intercepting = false; 
        } else {
            toastLog("❌ 答案不匹配（需完全一致），退回桌面。正确答案是：" + standardAnswer);
            dialog.dismiss();
            home(); 
            intercepting = false;
        }
    }).on("negative", function() {
        toastLog("你选择了放弃");
        home();
        intercepting = false;
    }).show();

    setTimeout(function() {
        if (intercepting) {
            toastLog("⏰ 超时，视为放弃");
            home();
            intercepting = false;
        }
    }, ANSWER_TIMEOUT);
}